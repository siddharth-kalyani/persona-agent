def test_vtt_attributed_and_unattributed() -> None:
    attributed = (
        "﻿WEBVTT\n\nNOTE generated by Teams\nsecond note line\n\n"
        "0f2c-1/12-0\n00:00:01.500 --> 00:00:04.000\n<v Lisa Chen>We need the rollback</v>\n\n"
        "0f2c-1/13-0\n00:00:04.100 --> 00:00:06.000\n<v Lisa Chen>tested &amp; signed off.</v>\n\n"
        "-00:00:02.000 --> 00:00:01.000\n<v John Miller (Guest)>Earlier words\n\n"
        "01:02:03.004 --> 01:02:05.000\n<v.loud Priya Nair><i>Late</i> point</v>\n"
    )
    cues = vtt.parse(attributed, attributed=True)
    assert [(c.speaker, c.text) for c in cues] == [
        ("Lisa Chen", "We need the rollback"),
        ("Lisa Chen", "tested & signed off."),
        ("John Miller (Guest)", "Earlier words"),
        ("Priya Nair", "Late point"),
    ]
    assert cues[2].start_ms == -2000 and cues[3].start_ms == 3_723_004
    turns = vtt.turns(cues)
    assert turns[1].text == "We need the rollback tested & signed off."  # one speaker, close in time
    assert turns[0].speaker == "John Miller (Guest)"  # ordered by time
    unattributed = (
        "00:00:01.500 --> 00:00:04.000 \n\nHello, thanks for joining. \n\n"
        "00:00:04.000 --> 00:00:07.200 \n\nGlad to be here. \n"
    )
    plain = vtt.parse(unattributed, attributed=False)
    assert [(c.speaker, c.text) for c in plain] == [(None, "Hello, thanks for joining."), (None, "Glad to be here.")]


def test_series_occurrences_take_their_own_transcripts() -> None:
    def ev(day: int) -> Event:
        start = datetime(2026, 10, day, 4, 30, tzinfo=UTC)
        return Event(f"e{day}", "Sync", start, start + timedelta(hours=1), None, series_id="s", is_online=True)

    series = [ev(6), ev(13), ev(20)]
    refs = [TranscriptRef(f"t{d}", "m", datetime(2026, 10, d, 4, 32, tzinfo=UTC)) for d in (6, 13, 13, 20)]
    assert [r.id for r in ingest.occurrence_transcripts(series[1], refs, series)] == ["t13", "t13"]
    late = TranscriptRef("late", "m", datetime(2026, 10, 13, 7, 0, tzinfo=UTC))  # transcription restarted later
    assert ingest.occurrence_transcripts(series[1], [late], series) == [late]


