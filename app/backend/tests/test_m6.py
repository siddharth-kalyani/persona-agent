async def _scan(client: httpx.AsyncClient, h: dict) -> dict:
    ingest.THROTTLE._last.clear()
    resp = await client.post("/api/meetings/scan", headers=h)
    assert resp.status_code == 200, resp.text
    return resp.json()


async def _scan_all(client: httpx.AsyncClient, h: dict) -> dict:
    total: dict[str, Any] = {"stored": 0, "promises": 0, "leftOut": 0, "excluded": 0}
    for _ in range(5):
        r = await _scan(client, h)
        for k in total:
            total[k] += r[k]
        if not r["pending"]:
            break
    return total


async def _meetings(client: httpx.AsyncClient, h: dict) -> dict:
    resp = await client.get("/api/meetings", headers=h)
    assert resp.status_code == 200, resp.text
    return resp.json()


async def _meeting(client: httpx.AsyncClient, h: dict, title: str, nth: int = 0) -> dict:
    items = [m for m in (await _meetings(client, h))["items"] if m["title"] == title]
    resp = await client.get(f"/api/meetings/{items[nth]['id']}", headers=h)
    assert resp.status_code == 200, resp.text
    return resp.json()


async def _ask(client: httpx.AsyncClient, h: dict, question: str, **extra: Any) -> dict:
    resp = await client.post("/api/meetings/ask", json={"question": question, **extra}, headers=h)
    assert resp.status_code == 200, resp.text
    return resp.json()


