async def test_excluded_meetings_are_never_read(client: httpx.AsyncClient, scanned: dict, app_state: AppState) -> None:
    h = scanned
    await _review(client, h)
    series = next(
        s for s in await _sources(client, h, "meetings") if s["kind"] == "series" and s["label"] == "Acme weekly sync"
    )
    assert (
        await client.post("/api/controls/rules", json={"kind": "series", "id": series["id"]}, headers=h)
    ).status_code == 201
    emily = _find(await _sources(client, h, "people"), "Emily Park")
