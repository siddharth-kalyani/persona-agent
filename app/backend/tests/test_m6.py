def _turn(n: int, speaker: str | None, side: str, words: str) -> Turn:
    return Turn(n, n * 30_000, n * 30_000 + 20_000, speaker, side, words)  # type: ignore[arg-type]


ME, LISA, RAHUL = "⟦ME.full⟧", "⟦PERSON_aaaaaaaa.full⟧", "⟦PERSON_bbbbbbbb⟧"


def test_offline_notes_kinds_owners_and_due_dates() -> None:
    turns = [
        _turn(0, LISA, "external", "The new reports must load in under three seconds."),
        _turn(1, ME, "me", "Understood. I'll share the cutover runbook by Thursday EOD."),
        _turn(2, LISA, "external", f"{RAHUL}, can you send the defect list by tomorrow?"),
        _turn(3, LISA, "external", "Agreed, let's go with a weekend go-live."),
        _turn(4, ME, "me", "What's the plan if the certification slips?"),
        _turn(5, ME, "me", "Maybe we could pilot with claims first."),
        _turn(6, LISA, "external", "My concern is that the window looks tight."),
        _turn(7, LISA, "external", "We haven't decided on the vendor yet. Thanks everyone."),
        _turn(8, ME, "me", "I need a minute."),
    ]
    found = {(a.kind, a.turn): a for a in offline_atoms(turns, started_at=WED, tz=IST)}
    assert set(found) == {
        ("requirement", 0), ("commitment", 1), ("action_item", 2), ("decision", 3), ("open_question", 4),
        ("idea", 5), ("risk", 6),
    }  # fmt: skip
    promise = found[("commitment", 1)]
    assert promise.text == "Share the cutover runbook" and promise.owner == ME
    assert promise.due_at == datetime(2026, 10, 15, 12, 30, tzinfo=UTC)  # Thursday 18:00 in India
    ask = found[("action_item", 2)]
    assert ask.owner == "⟦PERSON_bbbbbbbb.full⟧" and ask.due_phrase == "by tomorrow"
    # In a two-person meeting, "please prepare…" is for the other one.
    pair = [_turn(0, LISA, "internal", "Please prepare the Q4 plan before Thursday."), _turn(1, ME, "me", "Sure.")]
    assert offline_atoms(pair, started_at=WED, tz=IST)[0].owner == ME


def test_model_notes_are_held_to_the_transcript() -> None:
    window = [
        _turn(4, LISA, "external", "We need audit logs for every access."),
        _turn(5, ME, "me", "I'll send the plan by Friday."),
    ]
    raw = """```json
    {"atoms": [
      {"type": "requirement", "turn": 4, "quote": "We need audit logs for every access.", "summary": "Audit logs"},
      {"type": "requirement", "turn": 4, "quote": "We need encryption.", "summary": "Encryption"},
      {"type": "decision", "turn": 9, "quote": "x", "summary": "y"},
      {"type": "commitment", "turn": 5, "quote": "I'll send the plan by Friday.", "summary": "Send the plan",
       "owner": "⟦PERSON_aaaaaaaa.full⟧", "due": "by Friday"},
      {"type": "idea", "turn": 4, "quote": "We need audit logs for every access.", "summary": "Ask ⟦PERSON_deadbeef⟧"},
      {"type": "gossip", "turn": 4, "quote": "We need audit logs for every access.", "summary": "z"}
    ]}
    ```"""
    found = parse_atoms(raw, window, {LISA, ME}, started_at=WED, tz=IST)
    assert found is not None
    assert [(a.kind, a.text) for a in found] == [("requirement", "Audit logs"), ("commitment", "Send the plan")]
    assert found[1].owner == ME  # who promised is who said it, never the model's say
    assert found[1].due_at == datetime(2026, 10, 16, 12, 30, tzinfo=UTC)
    assert parse_atoms("not json", window, set(), started_at=WED, tz=IST) is None


