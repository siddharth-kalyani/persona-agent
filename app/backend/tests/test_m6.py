async def test_forget_a_meeting_and_correct_a_speaker(client: httpx.AsyncClient, scanned: dict) -> None:
    h = scanned
    await _review(client, h)
    await _scan_all(client, h)
    one = await _meeting(client, h, "Meera / you 1:1")
    me = next(p for p in one["people"] if p["side"] == "me")
    meera = next(p for p in one["people"] if p["name"] == "Meera Iyer")

    async def promised() -> set[str]:
        return {
            c["what"]
            for c in (await client.get("/api/commitments", headers=h)).json()["items"]
            if c["channel"] == "meeting"
        }

    assert "Send you the shortlist" in await promised()
    url = f"/api/meetings/{one['id']}/speakers"
    assert (await client.put(url, json={"fromId": me["id"], "toId": meera["id"]}, headers=h)).status_code == 204
    after = await _meeting(client, h, "Meera / you 1:1")
    assert all(t["speaker"] == "Meera Iyer" for t in after["transcript"])
    assert "Send you the shortlist" not in await promised()  # not your promise after all
    # Moving words back (here: all of the meeting's) makes them yours again.
    assert (await client.put(url, json={"fromId": meera["id"], "toId": me["id"]}, headers=h)).status_code == 204
    assert "Send you the shortlist" in await promised()
    assert (
        await client.put(url, json={"fromId": "⟦PERSON_00000000.full⟧", "toId": None}, headers=h)
    ).status_code == 422

    # A wrong note can be hidden; forgetting a meeting removes it for good.
    note = after["notesList"][0]
    assert (
        await client.put(f"/api/meetings/notes/{note['id']}", json={"action": "dismiss"}, headers=h)
    ).status_code == 204
    assert (await client.delete(f"/api/meetings/{one['id']}", headers=h)).status_code == 204
    assert (await client.get(f"/api/meetings/{one['id']}", headers=h)).status_code == 404
    await _scan_all(client, h)
    assert "Meera / you 1:1" not in {m["title"] for m in (await _meetings(client, h))["items"]}
    assert not {"Send you the shortlist"} & await promised()


