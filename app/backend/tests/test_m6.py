@pytest.mark.parametrize(
    ("question", "day", "at", "span"),
    [
        ("what did we decide yesterday?", date(2026, 10, 13), None, None),
        ("the client's requirements in Tuesday's meeting", date(2026, 10, 13), None, None),
        ("last Wednesday's sync", date(2026, 10, 7), None, None),
        ("the 4 pm meeting on Monday", date(2026, 10, 12), time(16), None),
        ("what was said at 4 today", date(2026, 10, 14), time(16), None),
        ("ideas from 14 Oct", date(2026, 10, 14), None, None),
        ("risks raised 3 days ago", date(2026, 10, 11), None, None),
        ("decisions last week", None, None, (date(2026, 10, 5), date(2026, 10, 12))),
        ("the 10:30 standup", None, time(10, 30), None),
    ],
)
def test_time_is_resolved_in_code(question: str, day: date | None, at: time | None, span: tuple | None) -> None:
    w = resolve(question, WED, IST, lookback=timedelta(days=30))
    assert w.explicit
    assert w.day == day and w.at == at
    if span:
        assert (w.start.date(), w.end.date()) == span
    morning = resolve("what came up this morning?", WED, IST, lookback=timedelta(days=30))
    assert (morning.start.hour, morning.end.hour) == (8, 12) and morning.start.tzinfo == IST


def test_the_4pm_meeting_asks_which_when_two_match() -> None:
    class Row:
        def __init__(self, i: str, h: int, m: int) -> None:
            self.id, self.starts_at = i, datetime(2026, 10, 13, h, m, tzinfo=IST)

    rows = [Row("a", 16, 0), Row("b", 16, 0), Row("c", 11, 0)]
    q = asking.parse_question("what did we decide in the 4 pm meeting yesterday?", WED, IST, {})
    chosen, ambiguous, cands = asking.choose_episodes(rows, q, IST, {"a": "Sync", "b": "Review", "c": "Other"})
    assert chosen == [] and ambiguous and {c.id for c in cands} == {"a", "b"}
    q = asking.parse_question("what did we decide in the 4 pm review yesterday?", WED, IST, {})
    chosen, ambiguous, _ = asking.choose_episodes(rows, q, IST, {"a": "Sync", "b": "Review", "c": "Other"})
    assert [c.id for c in chosen] == ["b"] and not ambiguous  # the title settles it


